const fs = require("fs");
const path = require("path");

const projectRoot = path.resolve(__dirname, "..");
const assetsRoot = path.join(projectRoot, "assets");
const appAssetsRoot = path.join(assetsRoot, "AppAssets");
const outputFile = path.join(assetsRoot, "imageMap.js");

function toPosixPath(filePath) {
  return filePath.split(path.sep).join("/");
}

function walkForGifs(dirPath) {
  const entries = fs.readdirSync(dirPath, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry.name);

    if (entry.isDirectory()) {
      files.push(...walkForGifs(fullPath));
      continue;
    }

    if (entry.isFile() && path.extname(entry.name).toLowerCase() === ".gif") {
      files.push(fullPath);
    }
  }

  return files;
}

if (!fs.existsSync(appAssetsRoot)) {
  throw new Error(`AppAssets folder not found: ${appAssetsRoot}`);
}

const gifFiles = walkForGifs(appAssetsRoot)
  .map((absolutePath) => path.relative(appAssetsRoot, absolutePath))
  .sort((a, b) => a.localeCompare(b));

const lines = [
  "// Auto-generated by scripts/generate-image-map.js",
  "// Do not edit this file manually.",
  "",
  "const imageMap = {",
  ...gifFiles.map((relativePath) => {
    const normalizedRelativePath = toPosixPath(relativePath);
    const requirePath = `./AppAssets/${normalizedRelativePath}`;
    return `  ${JSON.stringify(normalizedRelativePath)}: require(${JSON.stringify(requirePath)}),`;
  }),
  "};",
  "",
  "export default imageMap;",
  "export { imageMap };",
  "",
];

fs.writeFileSync(outputFile, lines.join("\n"), "utf8");

console.log(`Generated ${path.relative(projectRoot, outputFile)} with ${gifFiles.length} GIF entries.`);
